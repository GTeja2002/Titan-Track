// Generates the web hosting security headers from one definition:
//   public/_headers   (Netlify, Cloudflare Pages)
//   vercel.json       (Vercel)
// Run after changing index.html's inline script:  npm run headers
// (src/lib/securityHeaders.test.js fails if they are out of date.)
//
// These apply to the hosted WEBSITE only. The Android app is served by
// Capacitor, which injects its own inline bridge script, so a strict CSP is
// not applied inside the APK.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

export function inlineScriptHashes(html) {
  const re = /<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g;
  const out = [];
  let m;
  // Browsers normalise CRLF/CR line endings to LF while parsing HTML, and
  // hash the script text *after* that — so hash the same normalised text,
  // or a file saved with Windows line endings never matches.
  while ((m = re.exec(html))) {
    const text = m[1].split('\r\n').join('\n').split('\r').join('\n');
    out.push(`'sha256-${createHash('sha256').update(text).digest('base64')}'`);
  }
  return out;
}

export function buildHeaders(html) {
  const csp = [
    "default-src 'self'",
    // App bundle, the one inline script (by hash), Google sign-in on the web.
    `script-src 'self' ${inlineScriptHashes(html).join(' ')} https://accounts.google.com`,
    // React sets style attributes; Google Fonts and the Google button add CSS.
    "style-src 'self' 'unsafe-inline' https://fonts.googleapis.com https://accounts.google.com",
    "font-src 'self' https://fonts.gstatic.com",
    "img-src 'self' data: blob: https://*.googleusercontent.com",
    "media-src 'self'",
    // Supabase (REST, auth, realtime) and Google sign-in.
    "connect-src 'self' https://*.supabase.co wss://*.supabase.co https://accounts.google.com",
    "frame-src https://accounts.google.com",
    "worker-src 'self'",
    "manifest-src 'self'",
    "object-src 'none'",
    "base-uri 'self'",
    "form-action 'self'",
    "frame-ancestors 'none'",
    'upgrade-insecure-requests',
  ].join('; ');

  return {
    'Content-Security-Policy': csp,
    'Strict-Transport-Security': 'max-age=31536000; includeSubDomains',
    'X-Content-Type-Options': 'nosniff',
    'X-Frame-Options': 'DENY',
    'Referrer-Policy': 'strict-origin-when-cross-origin',
    'Permissions-Policy': 'camera=(), microphone=(), geolocation=(), payment=(), usb=()',
    'Cross-Origin-Opener-Policy': 'same-origin-allow-popups',
  };
}

export function renderNetlify(headers) {
  return `# Generated by scripts/security-headers.mjs — do not edit by hand.\n/*\n${Object.entries(headers).map(([k, v]) => `  ${k}: ${v}`).join('\n')}\n`;
}

export function renderVercel(headers) {
  return `${JSON.stringify({
    headers: [{ source: '/(.*)', headers: Object.entries(headers).map(([key, value]) => ({ key, value })) }],
  }, null, 2)}\n`;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const headers = buildHeaders(readFileSync(resolve(root, 'index.html'), 'utf8'));
  writeFileSync(resolve(root, 'public/_headers'), renderNetlify(headers));
  writeFileSync(resolve(root, 'vercel.json'), renderVercel(headers));
  console.log('wrote public/_headers and vercel.json');
}
